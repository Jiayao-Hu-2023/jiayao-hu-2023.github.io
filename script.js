// 获取当前时间字符串
function getTimeStr() {
    const now = new Date();
    return now.getHours().toString().padStart(2, '0') + ':' + now.getMinutes().toString().padStart(2, '0');
}

// 随机选择答案
function getRandomAnswer() {
    const answers = getCurrentAnswers();
    return answers[Math.floor(Math.random() * answers.length)];
}

